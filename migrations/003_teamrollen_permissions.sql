    ('settings.manage_kpis',   'settings',  'Eigene Kennzahlen verwalten (Phase 3, noch ungenutzt)')
on conflict (key) do nothing;

-- ── Systemrollen je bestehendem Tenant anlegen ───────────────────────────────
-- Owner/Admin bekommen ALLE Permissions, Mitarbeiter/Nur-Lesen eine Teilmenge
-- (siehe estimateiq/angebot/permissions.py::SYSTEMROLLEN – hier synchron
-- gehalten). do-Block, weil pro Tenant iteriert werden muss.

do $$
declare
    t record;
    r_owner bigint; r_admin bigint; r_mitarbeiter bigint; r_nurlesen bigint;
begin
    for t in select id from tenants loop
        insert into teamrollen (tenant_id, name, is_system)
            values (t.id, 'Owner', true)
            on conflict (tenant_id, name) do nothing;
        insert into teamrollen (tenant_id, name, is_system)
            values (t.id, 'Admin', true)
            on conflict (tenant_id, name) do nothing;
        insert into teamrollen (tenant_id, name, is_system)
            values (t.id, 'Mitarbeiter', true)
            on conflict (tenant_id, name) do nothing;
        insert into teamrollen (tenant_id, name, is_system)
            values (t.id, 'Nur-Lesen', true)
            on conflict (tenant_id, name) do nothing;

        select id into r_owner       from teamrollen where tenant_id = t.id and name = 'Owner';
        select id into r_admin       from teamrollen where tenant_id = t.id and name = 'Admin';
        select id into r_mitarbeiter from teamrollen where tenant_id = t.id and name = 'Mitarbeiter';
        select id into r_nurlesen    from teamrollen where tenant_id = t.id and name = 'Nur-Lesen';

        -- Owner + Admin: alle Permissions
        insert into teamrolle_permissions (teamrolle_id, permission_key)
            select r_owner, key from permissions
            on conflict do nothing;
        insert into teamrolle_permissions (teamrolle_id, permission_key)
            select r_admin, key from permissions
            on conflict do nothing;

        -- Mitarbeiter
        insert into teamrolle_permissions (teamrolle_id, permission_key)
            select r_mitarbeiter, key from unnest(array[
                'dashboard.view','projekte.erstellen','projekte.bearbeiten',
                'projekte.loeschen','projekte.status_aendern',
                'positionen.bearbeiten','import.durchfuehren'
            ]) as key
            on conflict do nothing;

        -- Nur-Lesen
        insert into teamrolle_permissions (teamrolle_id, permission_key)
            select r_nurlesen, key from unnest(array[
                'dashboard.view','projekte.alle_ansehen','projekte.marge_einsehen'
            ]) as key
            on conflict do nothing;
    end loop;
end $$;

-- ── tenant_users erweitern + befüllen ────────────────────────────────────────

alter table tenant_users add column if not exists teamrolle_id bigint references teamrollen(id);
alter table tenant_users add column if not exists status text not null default 'aktiv';

-- Backfill: rolle='admin' → Owner, rolle='mitglied' → Mitarbeiter, je Tenant.
update tenant_users tu
set teamrolle_id = tr.id
from teamrollen tr
where tu.teamrolle_id is null
  and tr.tenant_id = tu.tenant_id
  and tr.name = case when tu.rolle = 'admin' then 'Owner' else 'Mitarbeiter' end;

-- Erst jetzt, nach dem Backfill, die Constraint erzwingen (Postgres kann das,
-- SQLite nicht – deshalb ist die Spalte dort dauerhaft nullable, siehe
-- estimateiq/angebot/database.py).
alter table tenant_users alter column teamrolle_id set not null;

-- Die alte rolle-Spalte bleibt physisch bestehen, wird ab sofort nirgends
-- mehr gelesen. Wird in Migration 004 gedroppt (bewusst getrennter Schritt).

