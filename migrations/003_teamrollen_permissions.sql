-- ── Neue Tabellen ─────────────────────────────────────────────────────────────

create table if not exists teamrollen (
    id           bigint generated by default as identity primary key,
    tenant_id    text not null references tenants(id) on delete cascade,
    name         varchar(100) not null,
    is_system    boolean not null default false,
    beschreibung text,
    erstellt_am  timestamptz not null default now(),
    constraint uq_teamrollen_tenant_name unique (tenant_id, name)
);
create index if not exists ix_teamrollen_tenant on teamrollen(tenant_id);

create table if not exists permissions (
    key          text primary key,
    bereich      varchar(50) not null,
    beschreibung text not null
);

create table if not exists teamrolle_permissions (
    teamrolle_id   bigint not null references teamrollen(id) on delete cascade,
    permission_key text not null references permissions(key) on delete cascade,
    primary key (teamrolle_id, permission_key)
);

create table if not exists audit_log (
    id             bigint generated by default as identity primary key,
    tenant_id      text not null references tenants(id) on delete cascade,
    actor_user_id  text not null,
    aktion         varchar(100) not null,
    ziel_typ       varchar(50) not null,
    ziel_id        varchar(100) not null,
    vorher         jsonb,
    nachher        jsonb,
    erstellt_am    timestamptz not null default now()
);
create index if not exists ix_audit_log_tenant on audit_log(tenant_id);

alter table teamrollen          enable row level security;
alter table permissions         enable row level security;
alter table teamrolle_permissions enable row level security;
alter table audit_log           enable row level security;

-- ── Permission-Katalog befüllen ──────────────────────────────────────────────
-- Muss synchron zu estimateiq/angebot/permissions.py::KATALOG gehalten werden.

insert into permissions (key, bereich, beschreibung) values
    ('dashboard.view',          'dashboard', 'Dashboard aufrufen'),
    ('projekte.erstellen',      'projekte',  'Neues Projekt/Angebot anlegen'),
    ('projekte.bearbeiten',     'projekte',  'Projekt bearbeiten (kombiniert mit Ownership)'),
    ('projekte.loeschen',       'projekte',  'Projekt löschen (kombiniert mit Ownership)'),
    ('projekte.status_aendern','projekte',  'Angebotsstatus ändern, Angebot/PDF erzeugen'),
    ('projekte.alle_ansehen',  'projekte',  'Alle Projekte im Tenant sehen (nicht nur eigene)'),
    ('projekte.marge_einsehen','projekte',  'Interne Kosten/Marge/Stundensätze einsehen'),
    ('positionen.bearbeiten',  'positionen','Leistungspositionen anlegen/ändern/löschen'),
    ('rollen.verwalten',       'rollen',    'Stundensatz-Rollen verwalten'),
    ('import.durchfuehren',    'import',    'CSV/Excel-Import durchführen'),
    ('settings.manage_users',  'settings',  'Team & Rollen verwalten'),
